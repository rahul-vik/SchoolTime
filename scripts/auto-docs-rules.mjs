import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";

const root = process.cwd();
const docsDir = path.join(root, "docs");

const args = process.argv.slice(2);
const argMap = new Map();
for (let i = 0; i < args.length; i += 1) {
  const key = args[i];
  const val = args[i + 1];
  if (key?.startsWith("--") && val && !val.startsWith("--")) {
    argMap.set(key, val);
    i += 1;
  }
}

function run(command, fallback = "") {
  try {
    return execSync(command, { cwd: root, stdio: ["ignore", "pipe", "pipe"] }).toString("utf8").trim();
  } catch {
    return fallback;
  }
}

function readRuleMetadata(filePath) {
  const raw = fs.readFileSync(filePath, "utf8");
  const lines = raw.split(/\r?\n/);
  if (lines[0] !== "---") return { description: "", alwaysApply: "", globs: "" };
  let i = 1;
  const meta = {};
  while (i < lines.length && lines[i] !== "---") {
    const line = lines[i];
    const idx = line.indexOf(":");
    if (idx > 0) {
      const k = line.slice(0, idx).trim();
      const v = line.slice(idx + 1).trim();
      meta[k] = v;
    }
    i += 1;
  }
  return {
    description: meta.description || "",
    alwaysApply: meta.alwaysApply || "",
    globs: meta.globs || "",
  };
}

function ensureDocsDir() {
  if (!fs.existsSync(docsDir)) fs.mkdirSync(docsDir, { recursive: true });
}

function getChangedFiles(base, head) {
  const safeBase = base && base !== "0000000000000000000000000000000000000000" ? base : "";
  if (safeBase && head) {
    const out = run(`git diff --name-only ${safeBase} ${head}`);
    if (out) return out.split(/\r?\n/).filter(Boolean);
  }
  const out = run("git diff --name-only HEAD~1 HEAD");
  return out ? out.split(/\r?\n/).filter(Boolean) : [];
}

function buildAutoChangelog() {
  const log = run('git log --date=short --pretty=format:"%h|%ad|%an|%s" -n 80');
  const rows = log ? log.split(/\r?\n/).filter(Boolean) : [];
  const generatedAt = new Date().toISOString();

  const body = [
    "# Auto Changelog",
    "",
    "> This file is generated by `scripts/auto-docs-rules.mjs`. Do not edit manually.",
    "",
    `Last generated: ${generatedAt}`,
    "",
    "## Recent Commits",
    "",
  ];

  if (!rows.length) {
    body.push("- No commits available.");
  } else {
    for (const row of rows) {
      const [sha, date, author, subject] = row.split("|");
      body.push(`- ${date} \`${sha}\` — ${subject} _(by ${author})_`);
    }
  }
  body.push("");
  return `${body.join("\n")}\n`;
}

function buildAutoRulesStatus(changedFiles) {
  const rulesDir = path.join(root, ".cursor", "rules");
  const ruleFiles = fs.existsSync(rulesDir)
    ? fs.readdirSync(rulesDir).filter((f) => f.endsWith(".mdc")).sort()
    : [];

  const ruleRows = ruleFiles.map((file) => {
    const abs = path.join(rulesDir, file);
    const meta = readRuleMetadata(abs);
    return {
      file,
      description: meta.description || "(no description)",
      alwaysApply: meta.alwaysApply || "false",
      globs: meta.globs || "-",
    };
  });

  const categories = [
    {
      id: "Frontend",
      matches: (f) => f.startsWith("src/"),
      rule: "schooltime-frontend-react.mdc",
      hint: "UI behavior, feature flow, React structure",
    },
    {
      id: "Backend API",
      matches: (f) => f.startsWith("server/"),
      rule: "schooltime-backend-api.mdc",
      hint: "Routes, DB contract, auth, response semantics",
    },
    {
      id: "Export Pipeline",
      matches: (f) => f.includes("exportService") || f.startsWith("Results/"),
      rule: "schooltime-exports.mdc",
      hint: "PDF/Excel parity and export integrity",
    },
    {
      id: "Branch/Release",
      matches: (f) => f.startsWith(".github/") || f.startsWith("open-dev.bat"),
      rule: "schooltime-branch-release-policy.mdc",
      hint: "Branch safety, release gating, PR hygiene",
    },
    {
      id: "Core Standards",
      matches: (f) => f.startsWith("docs/") || f.startsWith(".cursor/rules/") || f === "AGENTS.md",
      rule: "schooltime-core.mdc",
      hint: "Cross-cutting conventions and delivery quality",
    },
  ];

  const impacted = categories
    .map((c) => {
      const files = changedFiles.filter((f) => c.matches(f));
      if (!files.length) return null;
      return { ...c, files };
    })
    .filter(Boolean);

  const generatedAt = new Date().toISOString();
  const body = [
    "# Auto Rules Intelligence",
    "",
    "> This file is generated by `scripts/auto-docs-rules.mjs`. Do not edit manually.",
    "",
    `Last generated: ${generatedAt}`,
    "",
    "## Registered Rule Files",
    "",
    "| Rule file | alwaysApply | globs | Description |",
    "| --- | --- | --- | --- |",
    ...ruleRows.map((r) => `| \`${r.file}\` | \`${r.alwaysApply}\` | \`${r.globs}\` | ${r.description} |`),
    "",
    "## Current Change Impact (Heuristic)",
    "",
  ];

  if (!changedFiles.length) {
    body.push("- No changed files detected for this run.");
  } else if (!impacted.length) {
    body.push("- Changes detected but no rule category match. Review `schooltime-core.mdc` manually.");
  } else {
    for (const area of impacted) {
      body.push(`### ${area.id}`);
      body.push(`- Suggested rule focus: \`${area.rule}\``);
      body.push(`- Why: ${area.hint}`);
      body.push(`- Changed files: ${area.files.map((f) => `\`${f}\``).join(", ")}`);
      body.push("");
    }
  }

  body.push("## Automation Intent");
  body.push("- Keep project changes automatically documented after every push.");
  body.push("- Surface likely rule touch points automatically for maintainers and AI tooling.");
  body.push("- Preserve manual authority: humans still decide final rule wording.");
  body.push("");
  return `${body.join("\n")}\n`;
}

function main() {
  ensureDocsDir();

  const base = argMap.get("--base") || process.env.GITHUB_EVENT_BEFORE || "";
  const head = argMap.get("--head") || process.env.GITHUB_SHA || "";
  const changedFiles = getChangedFiles(base, head);

  fs.writeFileSync(path.join(docsDir, "AUTO_CHANGELOG.md"), buildAutoChangelog(), "utf8");
  fs.writeFileSync(path.join(docsDir, "AUTO_RULES_INTELLIGENCE.md"), buildAutoRulesStatus(changedFiles), "utf8");

  console.log("Updated docs/AUTO_CHANGELOG.md and docs/AUTO_RULES_INTELLIGENCE.md");
}

main();
